async page => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let loads=0,supportsPause=true;
  await page.route('https://game.example.test/**',async route=>{
    loads++;
    await route.fulfill({contentType:'text/html',body:`<!doctype html><meta charset="utf-8"><button onclick="score++;document.querySelector('output').textContent=score">增加分数</button><output>0</output><script>
      window.score=0;window.ticks=0;window.paused=false;window.docId=Math.random();setInterval(()=>{if(!paused)ticks++},20);
      ${supportsPause ? `addEventListener('message',e=>{const d=e.data;if(d.type==='beegame:hello')e.source.postMessage({version:1,type:'beegame:capabilities',requestId:d.requestId,pause:true},e.origin);if(d.type==='beegame:set-paused'){paused=d.paused;e.source.postMessage({version:1,type:'beegame:paused',requestId:d.requestId,paused},e.origin);}});` : ''}
    </script>`});
  });
  // Open the harness URL printed by server.cjs before running this scenario.
  await page.goto(new URL('/', page.url()).href);
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.evaluate(() => {
    for (const key of ['dsh-beegame-hud-position', 'dsh-beegame-window-position', 'dsh-beegame-window-size']) localStorage.removeItem(key);
  });
  await page.reload();
  await page.getByRole('button',{name:'Keepalive Test',exact:true}).first().click();
  if(await page.locator('.bg_note').count())throw new Error('Removed player description still displayed');
  if(await page.getByRole('button',{name:'缩小到悬浮窗（保留当前游戏）',exact:true}).locator('rect').count())throw new Error('Minimize icon still has a square');
  const frame=page.frameLocator('iframe');
  await frame.getByRole('button',{name:'增加分数'}).click();
  const original=page.frames().find(f=>f.url().startsWith('https://game.example.test'));
  const docId=await original.evaluate(()=>docId);
  await page.evaluate(()=>{window.originalFrame=document.querySelector('iframe');window.originalWindow=originalFrame.contentWindow;});
  const assert=(condition,message)=>{if(!condition)throw new Error(message);};
  const retained=async label=>{
    assert(loads===1,label+': unexpected reload '+loads);
    assert(await page.evaluate(()=>document.querySelector('iframe')===originalFrame&&originalFrame.isConnected&&originalFrame.contentWindow===originalWindow),label+': frame identity changed');
    assert(await original.evaluate(()=>score===1&&docId===window.docId),label+': score changed');
    assert(await original.evaluate(()=>window.docId)===docId,label+': document replaced');
  };
  const pill=page.getByRole('button',{name:'DSH 任务动态',exact:true});
  const hud=page.locator('.bg_hud');
  const hudBefore=await hud.boundingBox();
  const pillBox=await pill.boundingBox();
  await page.mouse.move(pillBox.x+pillBox.width/2,pillBox.y+pillBox.height/2);
  await page.mouse.down();
  await page.mouse.move(pillBox.x+pillBox.width/2-180,pillBox.y+pillBox.height/2+90,{steps:8});
  await page.mouse.up();
  const hudAfter=await hud.boundingBox();
  assert(Math.abs(hudAfter.x-(hudBefore.x-180))<2&&Math.abs(hudAfter.y-(hudBefore.y+90))<2,'HUD drag failed');
  assert(await pill.getAttribute('aria-expanded')==='false','HUD drag opened task list');
  await pill.click();
  assert(await pill.getAttribute('aria-expanded')==='true','HUD click no longer opens tasks');
  await page.locator('.bg_hud-list').waitFor();
  await pill.click();
  await pill.focus();await page.keyboard.press('ArrowLeft');
  assert(Math.abs((await hud.boundingBox()).x-(hudAfter.x-16))<2,'HUD keyboard movement failed');
  await page.keyboard.press('Enter');
  assert(await pill.getAttribute('aria-expanded')==='true','HUD keyboard activation failed');
  await page.keyboard.press('Enter');
  const hudSaved=await hud.boundingBox();
  await retained('HUD drag');
  await page.getByRole('button',{name:'暂离，去会话',exact:true}).first().click();
  await page.getByRole('textbox',{name:'安排任务'}).fill('任务草稿：保留当前游戏');
  await page.getByText('游戏已确认暂停',{exact:true}).waitFor();
  const ticks=await original.evaluate(()=>ticks);
  await page.waitForTimeout(150);
  assert(await original.evaluate(()=>ticks)===ticks,'acknowledged pause did not stop simulated game');
  await retained('leave');
  const handle=page.getByRole('button',{name:'拖动游戏小窗 · Keepalive Test',exact:true});
  const before=await page.locator('.bg_persistent').boundingBox();
  const grip=await handle.boundingBox();
  await page.mouse.move(grip.x+grip.width/2,grip.y+grip.height/2);
  await page.mouse.down();
  await page.mouse.move(grip.x+grip.width/2-200,grip.y+grip.height/2-150,{steps:10});
  await page.mouse.up();
  const after=await page.locator('.bg_persistent').boundingBox();
  assert(Math.abs(after.x-(before.x-200))<2&&Math.abs(after.y-(before.y-150))<2,'drag did not move the window');
  await retained('drag away');
  await handle.focus();await page.keyboard.press('ArrowLeft');
  assert(Math.abs((await page.locator('.bg_persistent').boundingBox()).x-(after.x-16))<2,'keyboard movement failed');
  const savedPosition=await page.locator('.bg_persistent').boundingBox();
  await page.getByRole('button',{name:'返回游戏',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.bg_persistent').dataset.mode==='full');
  await page.waitForTimeout(100);
  assert(await original.evaluate(()=>ticks)>ticks,'game did not resume');
  await retained('return');
  assert(Math.abs((await hud.boundingBox()).x-hudSaved.x)<2,'HUD position lost after return');
  await page.getByRole('button',{name:'缩小到悬浮窗（保留当前游戏）',exact:true}).click();
  await retained('mini');
  const miniPosition=await page.locator('.bg_persistent').boundingBox();
  assert(Math.abs(miniPosition.x-savedPosition.x)<2,'floating position was lost on return');
  const miniGrip=await page.getByRole('button',{name:'拖动游戏小窗 · Keepalive Test',exact:true}).boundingBox();
  await page.mouse.move(miniGrip.x+30,miniGrip.y+10);await page.mouse.down();
  await page.mouse.move(miniGrip.x-30,miniGrip.y-20,{steps:5});await page.mouse.up();
  assert(Math.abs((await page.locator('.bg_persistent').boundingBox()).x-(miniPosition.x-60))<2,'mini window drag failed');
  await retained('drag mini');
  const mini=page.locator('.bg_persistent');
  const resize=async(edge,dx,dy)=>{
    const before=await mini.boundingBox();
    const grip=await page.locator(`.bg_resize-handle[data-edge="${edge}"]`).boundingBox();
    await page.mouse.move(grip.x+grip.width/2,grip.y+grip.height/2);
    await page.mouse.down();
    await page.mouse.move(grip.x+grip.width/2+dx,grip.y+grip.height/2+dy,{steps:6});
    await page.mouse.up();
    await retained('resize '+edge);
    return {before,after:await mini.boundingBox()};
  };
  // Move away from viewport boundaries so all eight directions can grow.
  await handle.focus();await page.keyboard.press('Home');
  const title=await handle.boundingBox();
  await page.mouse.move(title.x+20,title.y+16);await page.mouse.down();
  await page.mouse.move(title.x-480,title.y-164,{steps:6});await page.mouse.up();
  for(const edge of ['e','s','w','n','se','sw','ne','nw']){
    const dx=edge.includes('e')?20:edge.includes('w')?-20:0;
    const dy=edge.includes('s')?15:edge.includes('n')?-15:0;
    const {before,after}=await resize(edge,dx,dy);
    assert(Math.abs(after.width-before.width-Math.abs(dx))<2,'width resize failed: '+edge);
    assert(Math.abs(after.height-before.height-Math.abs(dy))<2,'height resize failed: '+edge);
    if(edge.includes('w'))assert(Math.abs(after.x+after.width-before.x-before.width)<2,'west opposite edge moved');
    if(edge.includes('n'))assert(Math.abs(after.y+after.height-before.y-before.height)<2,'north opposite edge moved');
  }
  const shrunkWidth=await resize('e',-90,0);
  assert(Math.abs(shrunkWidth.after.width-shrunkWidth.before.width+90)<2,'cannot narrow independently');
  const shrunkHeight=await resize('s',0,-70);
  assert(Math.abs(shrunkHeight.after.height-shrunkHeight.before.height+70)<2,'cannot shorten independently');
  const corner=page.locator('.bg_resize-handle[data-edge="se"]');
  await corner.focus();await page.keyboard.press('ArrowRight');
  assert(Math.abs((await mini.boundingBox()).width-shrunkHeight.after.width-16)<2,'keyboard resize failed');
  const customSize=await mini.boundingBox();
  await page.getByRole('button',{name:'返回游戏',exact:true}).click();
  assert(await page.locator('.bg_resize-handle').count()===0,'resize handles displayed in full mode');
  await page.getByRole('button',{name:'缩小到悬浮窗（保留当前游戏）',exact:true}).click();
  const restoredSize=await mini.boundingBox();
  assert(Math.abs(restoredSize.width-customSize.width)<2&&Math.abs(restoredSize.height-customSize.height)<2,'custom size lost on return');
  await page.screenshot({path:'output/playwright/resizable-mini.png'});
  await retained('resize round trip');
  await page.setViewportSize({width:520,height:400});
  await page.waitForTimeout(80);
  const clamped=await page.locator('.bg_persistent').boundingBox();
  assert(clamped.x>=0&&clamped.y>=0&&clamped.x+clamped.width<=520&&clamped.y+clamped.height<=400,'resized window escaped the viewport');
  const hudMini=await hud.boundingBox();const stageMini=await page.locator('.bg_stage').boundingBox();
  assert(hudMini.x>=stageMini.x&&hudMini.y>=stageMini.y&&hudMini.x+hudMini.width<=stageMini.x+stageMini.width&&hudMini.y+hudMini.height<=stageMini.y+stageMini.height,'HUD escaped the game bounds');
  await page.setViewportSize({width:1280,height:720});
  await resize('se',-2000,-2000);
  const minimum=await mini.boundingBox();
  assert(minimum.width===320&&minimum.height===200,'minimum size not enforced');
  await resize('se',2000,2000);
  const maximum=await mini.boundingBox();
  assert(maximum.x+maximum.width<=1272&&maximum.y+maximum.height<=712,'resize escaped viewport');
  await page.getByRole('button',{name:'会话',exact:true}).click();
  await retained('mini with unmounted main');
  await page.getByRole('button',{name:'返回游戏',exact:true}).click();
  await retained('expand');
  await page.getByRole('button',{name:'会话',exact:true}).click();
  await page.getByText('游戏已确认暂停',{exact:true}).waitFor();
  await retained('direct sidebar switch');
  await page.getByRole('button',{name:'返回游戏',exact:true}).click();
  if(await pill.getAttribute('aria-expanded')!=='true')await pill.click();
  await page.locator('.bg_hud-row').first().click();
  await page.getByRole('textbox',{name:'安排任务'}).waitFor();
  await retained('HUD switch');
  await page.getByRole('button',{name:'返回游戏',exact:true}).click();
  await page.getByRole('button',{name:'结束游戏',exact:true}).click();
  assert(await page.locator('iframe').count()===0,'explicit end retained iframe');
  supportsPause=false;
  await page.getByRole('button',{name:'Keepalive Test',exact:true}).first().click();
  await page.frameLocator('iframe').getByRole('button',{name:'增加分数'}).click();
  await page.getByRole('button',{name:'暂离，去会话',exact:true}).first().click();
  await page.getByRole('button',{name:'返回游戏',exact:true}).waitFor();
  assert(await page.locator('.bg_pause-status').count()===0,'unconfirmed pause description is still displayed');
  assert(await page.getByText('游戏已确认暂停',{exact:true}).count()===0,'unsupported game falsely marked paused');
  assert(errors.length===0,'page errors: '+errors.join(','));
  console.log(JSON.stringify({result:'PASS',sameIframe:true,sameContentWindow:true,sameDocument:true,retainedScore:1,loadsBeforeEnd:1,loadsAfterNewGame:loads,cooperativePause:true,unsupportedFallback:true,pageErrors:errors}));
  await page.screenshot({path:'output/playwright/away.png'});
  return {result:'PASS',hudDrag:true,hudClickAfterDrag:true,hudKeyboard:true,hudPositionRetained:true,hudBounds:true,removedDescription:true,plainMinimizeIcon:true,resizeEightDirections:true,resizeKeyboard:true,sizeRetained:true,resizeMinimum:true,dragAway:true,dragMini:true,keyboardMove:true,resizeClamp:true,positionRetained:true,gameLoadedOnce:true,scoreRetained:true,cooperativePause:true,pageErrors:errors};
}
